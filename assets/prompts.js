/* ==========================================================================
   prompts.js — 每一步的提示词
   设计原则：
   1) 一步一个明确产出，产出格式固定（JSON 或受限 Markdown），前端才敢直接渲染；
   2) 把「公众号阅读场景」写进约束（短段落、小标题、手机屏幕），而不是只说"写篇文章"；
   3) 改稿类请求一律回整篇正文，前端做整体替换 + 可撤销，避免增量打补丁打歪。
   ========================================================================== */
(function (global) {
  "use strict";

  const SYSTEM = [
    "你是一位在公众号上写了七八年的中文作者，也做过公众号编辑。",
    "你的稿子有一个特点：读者在地铁上单手划手机，也能一口气读完。",
    "你讨厌三样东西：空话套话（赋能、闭环、抓手）、堆砌形容词、以及把读者当外行却又不肯解释。",
    "你写作时遵守：一段话只说一件事；能用具体例子就不用抽象概念；数字和细节优先于形容词；不写正确的废话。",
  ].join("\n");

  const BAN = "不要出现「赋能」「闭环」「抓手」「生态位」「底层逻辑」这类词；不要写「本文由AI生成」；不要用 emoji 当装饰；不要用一连串感叹号。";

  /** 允许的排版语法（和 renderer.js 支持的语法保持一致） */
  const SYNTAX = [
    "排版语法（只能用这些）：",
    "- `## 小标题` 二级标题（3–5 个，不要用一级标题 #）",
    "- 普通段落，段落之间空一行",
    "- `**加粗**` 用来标出关键句，全篇不超过 8 处",
    "- `> 引用` 用来放一句能被单独截图的话，全篇 1–2 处",
    "- `- 列表项` 用来做并列要点，每组不超过 6 条",
    "- `:::tip 内容` 单独成段，用来放补充说明（最多 1 处，可不用）",
    "- 不要用表格、不要用代码块、不要用图片标记",
  ].join("\n");

  function base(ctx) {
    return [
      `主题／素材：${ctx.topic}`,
      `写作风格：${ctx.mode}`,
      `目标读者：${ctx.audience}`,
      `目标篇幅：约 ${ctx.length} 字`,
      ctx.extra ? `额外要求（必须遵守）：${ctx.extra}` : "",
    ]
      .filter(Boolean)
      .join("\n");
  }

  /* ── 1. 选题 + 标题 ────────────────────────────────────────────────── */
  function ideas(ctx) {
    return {
      system: SYSTEM,
      user: [
        base(ctx),
        "",
        "请先想清楚：这篇稿子要帮读者解决什么具体问题？读者读完会记住哪一句？",
        "",
        "然后输出 JSON（不要任何解释、不要 Markdown 代码块围栏），字段如下：",
        "{",
        '  "angle": "一句话说清这篇从哪个角度切入、凭什么值得读（40–70 字，具体，不要「全面解析」这种）",',
        '  "titles": [ {"title": "标题", "why": "为什么这个标题能让人点开（12 字内）"} ],  // 5 个，风格要有差异：一个具体数字型、一个疑问型、一个反常识型、一个利益承诺型、一个故事型',
        '  "summary": "公众号摘要，55 字以内，一句话勾住人",',
        '  "cover": "封面文案，12 字以内，可做大字标题"',
        "}",
        "",
        "标题要求：不超过 24 字；不用「震惊」「必看」这类词；每个标题都要能独立看懂在说什么。",
        BAN,
      ].join("\n"),
    };
  }

  /* ── 2. 大纲 ───────────────────────────────────────────────────────── */
  function outline(ctx, chosen) {
    return {
      system: SYSTEM,
      user: [
        base(ctx),
        "",
        `已经确定的标题：《${chosen.title}》`,
        `切入角度：${chosen.angle}`,
        "",
        "请给出这篇文章的大纲，纯文本 Markdown，格式：",
        "## 小标题",
        "- 这一段要讲什么（一句话）",
        "- 用什么例子／数据支撑",
        "",
        "要求：",
        "1. 4 个左右的小节，第一节必须在前 3 行内给出「读者为什么要往下读」的理由；",
        "2. 每节标注预计字数，总和接近目标篇幅；",
        "3. 最后一节要落到「读者今天就能做的一件事」，不要用「让我们一起期待」收尾。",
        "只输出大纲本身，不要开场白。",
      ].join("\n"),
    };
  }

  /* ── 3. 正文 ───────────────────────────────────────────────────────── */
  function article(ctx, chosen, outlineText) {
    return {
      system: SYSTEM,
      user: [
        base(ctx),
        "",
        `标题：《${chosen.title}》`,
        `摘要：${chosen.summary || ""}`,
        "",
        "这是已经确认的大纲，请严格按它写：",
        outlineText,
        "",
        SYNTAX,
        "",
        "写作要求：",
        "1. 开头两句话内必须出现具体场景或冲突，禁止「随着……的发展」「在当今时代」；",
        "2. 每个小节的段落数控制在 2–4 段，每段 2–4 行（手机屏幕上不超过 4 行）；",
        "3. 至少出现 2 处具体细节（时间、数字、原话、工具名、价格），不要空泛举例；",
        "4. 全文不要重复同一个观点两次；",
        "5. 结尾给一个可执行的动作，不要喊口号；",
        `6. 总字数要落在 ${Math.round(ctx.length * 0.9)}–${Math.round(ctx.length * 1.15)} 字之间。写完先自己数一遍，不够就补具体细节和例子，不要用形容词注水。`,
        "只输出正文 Markdown，不要重复标题，不要写「正文如下」之类的话。",
        BAN,
      ].join("\n"),
    };
  }

  /* ── 4. 改稿 ───────────────────────────────────────────────────────── */
  const ACTIONS = {
    口语: "把全文改得更像人说话：拆掉长句，把书面词换成日常说法，允许出现「其实」「说白了」这类口头衔接。观点和信息量一点都不能少。",
    钩子: "重写开头三段：用一个具体场景、一句反常识的话或一个真实数字把读者拽住，让人非往下看不可。后面的内容保持不变。",
    精简: "把全文压缩到原来的七成左右：删掉重复论述、形容词堆砌和过渡废话，保留所有具体细节和小标题结构。",
    案例: "补充 2 个具体、可信的例子（有人、有事、有结果），插到最需要支撑的那两段后面，不要新增小标题。",
    小标题: "把每个小标题改得更具体、更有信息量：让人只看小标题串起来也能知道全文讲了什么。正文相应微调。",
  };

  function revise(articleText, instruction, action) {
    const task = action && ACTIONS[action] ? ACTIONS[action] : instruction;
    return {
      system: SYSTEM,
      user: [
        "下面是公众号文章的正文 Markdown：",
        "----",
        articleText,
        "----",
        "",
        `修改要求：${task}`,
        "",
        "请输出修改后的完整正文（不是片段、不是差异说明），保持原有的 Markdown 排版语法与标题层级。",
        "如果要求里包含「只改某一段」，其余段落必须原样保留。",
        "不要输出任何解释、说明或前后缀，直接给正文。",
        BAN,
      ].join("\n"),
    };
  }

  /* ── 5. 发前体检 ───────────────────────────────────────────────────── */
  function checkup(articleText) {
    return {
      system: "你是一位严格但讲道理的公众号主编，负责在发布前给稿子挑毛病。你不奉承，也不为了显得专业而硬挑刺。",
      user: [
        "请审阅这篇公众号文章：",
        "----",
        articleText,
        "----",
        "",
        "输出 JSON（不要代码围栏、不要解释），结构：",
        "{",
        '  "scores": {"钩子": 0-10, "清晰": 0-10, "信息密度": 0-10, "手机阅读": 0-10, "可信度": 0-10},',
        '  "verdict": "一句话总评（30 字内）",',
        '  "fixes": ["最该改的 3 个地方，每条给出具体改法，不要泛泛而谈"]',
        "}",
        "评分标准：钩子=开头是否能让人不划走；清晰=读一遍能不能复述核心观点；信息密度=有没有废话；手机阅读=段落长度、小标题节奏是否适合手机；可信度=有没有具体细节支撑。",
      ].join("\n"),
    };
  }

  global.Prompts = { SYSTEM, ideas, outline, article, revise, checkup, ACTIONS };
})(typeof window !== "undefined" ? window : globalThis);
